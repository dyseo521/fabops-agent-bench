"""Digital Reference에서 fab.ttl이 정렬한 클래스·속성과 그 상위 계층만 뽑아 ontology/dr_subset.ttl로 쓴다.

LLM 프롬프트와 OWL RL 추론에 DR 전체(1,351 class)를 넣지 않기 위한 모듈 추출이다.
포함: 정렬 대상 + 이름 있는 상위 클래스·상위 속성의 폐포, 각 항목의 rdf:type, rdfs:label, skos:definition,
      rdfs:subClassOf / subPropertyOf, rdfs:domain / range, owl:inverseOf (대상이 이름 있는 IRI이고 서브셋 안에 있을 때)

예) python scripts/extract_dr_subset.py
"""
import os

import rdflib
from rdflib.namespace import OWL, RDF, RDFS, SKOS

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DR = os.path.join(ROOT, 'data', 'DigitalReference', 'DigitalReference.ttl')
FAB = os.path.join(ROOT, 'ontology', 'fab.ttl')
OUT = os.path.join(ROOT, 'ontology', 'dr_subset.ttl')
DR_NS = 'http://www.w3id.org/ecsel-dr'
FAB_NS = 'https://w3id.org/ontosemc/fab#'
COMMIT = 'db88755'


def main():
    dr = rdflib.Graph().parse(DR)
    fab = rdflib.Graph().parse(FAB)
    seeds = {o for p in (RDFS.subClassOf, RDFS.subPropertyOf) for s, o in fab.subject_objects(p)
             if str(s).startswith(FAB_NS) and str(o).startswith(DR_NS)}
    keep, todo = set(), list(seeds)
    while todo:
        x = todo.pop()
        if x in keep:
            continue
        keep.add(x)
        for p in (RDFS.subClassOf, RDFS.subPropertyOf):
            todo += [o for o in dr.objects(x, p) if isinstance(o, rdflib.URIRef) and str(o).startswith(DR_NS)]
    out = rdflib.Graph()
    for pfx, ns in dr.namespaces():
        if str(ns).startswith(DR_NS) or pfx in ('skos', 'owl', 'rdfs', 'rdf'):
            out.bind(pfx, ns)
    onto = rdflib.URIRef(DR_NS + '-subset')
    out.add((onto, RDF.type, OWL.Ontology))
    out.add((onto, RDFS.comment, rdflib.Literal(
        f'Module of the ECSEL Digital Reference (commit {COMMIT}) restricted to the classes and properties '
        f'aligned in fab.ttl and their named super-classes and super-properties. Generated by '
        f'scripts/extract_dr_subset.py.', lang='en')))
    for x in sorted(keep):
        for p in (RDF.type, RDFS.label, SKOS.definition, RDFS.comment):
            for o in dr.objects(x, p):
                if p != RDF.type or o in (OWL.Class, OWL.ObjectProperty, OWL.DatatypeProperty):
                    out.add((x, p, o))
        for p in (RDFS.subClassOf, RDFS.subPropertyOf, RDFS.domain, RDFS.range, OWL.inverseOf):
            for o in dr.objects(x, p):
                if o in keep:
                    out.add((x, p, o))
    header = (f'# Digital Reference 서브셋 (commit {COMMIT}). 자동 생성: scripts/extract_dr_subset.py\n'
              f'# fab.ttl이 정렬한 DR 클래스·속성 {len(seeds)}개 + 상위 계층. 직접 수정하지 않는다\n\n')
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write(header + out.serialize(format='turtle'))
    n_cls = len(set(out.subjects(RDF.type, OWL.Class)))
    n_prop = len(set(out.subjects(RDF.type, OWL.ObjectProperty)))
    print(f'{os.path.relpath(OUT, ROOT)}: 정렬 대상 {len(seeds)}, 포함 항목 {len(keep)} '
          f'(class {n_cls}, object property {n_prop}), triples {len(out)}')


if __name__ == '__main__':
    main()
